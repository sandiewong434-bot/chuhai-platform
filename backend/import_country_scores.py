    cursor = conn.cursor()

    # 清空旧数据
    cursor.execute("DELETE FROM country_scores")
    print(f"已清空 country_scores 表")

    today = date.today().isoformat()

    inserted = 0
    for code, name, tier, region in COUNTRIES:
        dim_scores = SCORES[code]
        total = calculate_total(dim_scores)
        level = calculate_level(total)

