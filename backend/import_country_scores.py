def calculate_level(score: float) -> str:
    if score >= 90:
        return "强烈推荐"
    elif score >= 75:
        return "推荐"
    elif score >= 60:
        return "谨慎推荐"
    elif score >= 40:
        return "不推荐"
    return "暂不推荐"


